TARGET = 10


def main():
    with open(RAW, encoding="utf-8") as f:
        data = json.load(f)

    next_id = 601
    added = 0
    total = 0

    for store in data["storeList"]:
        for cat in store["categories"]:
            key = (store["name"], cat["name"])
            if key not in PLAN:
                print("!! 未规划的分类:", key)
                continue
            plan = PLAN[key]
            holder = "products" if "products" in cat else "productList"
            items = cat.setdefault(holder, [])
            existing_names = {p["name"] for p in items}

            for (name, subtitle, price, origin, key_param, sales, stock) in plan["items"]:
                if len(items) >= TARGET:
                    break
                if name in existing_names:
                    continue
                items.append({
                    "id": next_id,
                    "name": name,
                    "subtitle": subtitle,
                    "price": float(price),
                    "originPrice": float(origin),
                    "sales": sales,
                    "stock": stock,
                    "icon": plan["icon"],
                    "params": list(plan["params"]) + [key_param],
                    "description": "%s，%s。%s 加持，%s 官方直营，支持七天无理由退货。" % (
                        name, subtitle, key_param, store["name"]),
                    "cover": plan["cover"],
                })
                next_id += 1
                added += 1

            # 不足 10 件时用同系列补充（保底）
            total += len(items)

    with open(RAW, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print("新增商品:", added)
    print("商品总数:", total)
    for store in data["storeList"]:
        counts = [len(c.get("products") or c.get("productList") or []) for c in store["categories"]]
        print("  %-10s %s" % (store["name"], counts))


if __name__ == "__main__":
    main()
